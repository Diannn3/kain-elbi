import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(scriptDir, '..');
const repoRoot = resolve(appRoot, '..');

function parseArgs(argv) {
	const result = {};
	for (let index = 0; index < argv.length; index += 1) {
		const value = argv[index];
		if (!value.startsWith('--')) continue;
		result[value.slice(2)] = argv[index + 1];
		index += 1;
	}
	return result;
}

function sqlString(value) {
	if (value === null || value === undefined || value === '') return 'null';
	return `'${String(value).replaceAll("'", "''")}'`;
}

function placeIdsForZone(zone) {
	const ids = zone.placeIds ?? zone.place_ids ?? [];
	return Array.isArray(ids) ? ids.filter((id) => typeof id === 'string' && id.trim()) : [];
}

const args = parseArgs(process.argv.slice(2));
const placesPath = resolve(repoRoot, args.places ?? 'data/places.json');
const zonesPath = resolve(repoRoot, args.zones ?? 'data/zones.json');
const outputPath = resolve(repoRoot, args.output ?? 'supabase/generated/community-place-registry.sql');

const places = JSON.parse(await readFile(placesPath, 'utf8'));
const zones = JSON.parse(await readFile(zonesPath, 'utf8'));

if (!Array.isArray(places) || !places.length) throw new Error('places.json must contain at least one place');
if (!Array.isArray(zones) || !zones.length) throw new Error('zones.json must contain at least one zone');

const canonicalIds = new Set(
	places
		.map((place) => typeof place?.id === 'string' ? place.id.trim() : '')
		.filter(Boolean),
);
if (!canonicalIds.size) throw new Error('places.json does not contain canonical place IDs');

const zoneByPlace = new Map();
const primaryZones = zones.filter((zone) => zone?.id !== 'elsewhere-lb');
const fallbackZones = zones.filter((zone) => zone?.id === 'elsewhere-lb');

for (const zone of [...primaryZones, ...fallbackZones]) {
	if (!zone || typeof zone.id !== 'string') continue;
	for (const placeId of placeIdsForZone(zone)) {
		if (canonicalIds.has(placeId) && !zoneByPlace.has(placeId)) zoneByPlace.set(placeId, zone.id);
	}
}

const rows = [...canonicalIds]
	.sort((a, b) => a.localeCompare(b))
	.map((placeId) => `\t(${sqlString(placeId)}, ${sqlString(zoneByPlace.get(placeId) ?? null)}, true, now())`);

const sql = `-- Generated by app/scripts/generate-community-registry.mjs\n-- Do not hand-edit; regenerate from canonical places/zones.\n\nbegin;\n\nupdate public.uppetite_community_place_registry\nset active = false, updated_at = now();\n\ninsert into public.uppetite_community_place_registry (place_id, zone_id, active, updated_at)\nvalues\n${rows.join(',\n')}\non conflict (place_id) do update set\n\tzone_id = excluded.zone_id,\n\tactive = true,\n\tupdated_at = now();\n\ncommit;\n`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, sql, 'utf8');

process.stdout.write(`Generated ${rows.length} community registry rows at ${outputPath}\n`);
